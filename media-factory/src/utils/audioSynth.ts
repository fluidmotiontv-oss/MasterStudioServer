/**
 * Calculates exact 432Hz Verdi frequency for a given MIDI note number.
 * Formula: f = 432 * 2^((midiNote - 69) / 12)
 */
export function getMidiNoteFrequency432(midiNote: number): number {
  return 432 * Math.pow(2, (midiNote - 69) / 12);
}

let audioCtx: AudioContext | null = null;
let isPlaying = false;
let playbackTimeoutIds: number[] = [];

export function getAudioContext(): AudioContext {
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
    audioCtx = new AudioContextClass();
  }
  if (audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

export function stopAudioPlayback() {
  playbackTimeoutIds.forEach(id => clearTimeout(id));
  playbackTimeoutIds = [];
  isPlaying = false;
}

/**
 * Plays a single note tuned to 432Hz.
 */
export function play432HzTone(midiNote: number, durationSec = 0.5, type: OscillatorType = 'sine', velocity = 0.8) {
  const ctx = getAudioContext();
  const freq = getMidiNoteFrequency432(midiNote);

  const osc = ctx.createOscillator();
  const gain = ctx.createGain();

  osc.type = type;
  osc.frequency.setValueAtTime(freq, ctx.currentTime);

  // Envelope
  const now = ctx.currentTime;
  const attack = 0.02;
  const decay = durationSec * 0.8;

  gain.gain.setValueAtTime(0.0001, now);
  gain.gain.exponentialRampToValueAtTime(velocity * 0.4, now + attack);
  gain.gain.exponentialRampToValueAtTime(0.0001, now + durationSec);

  osc.connect(gain);
  gain.connect(ctx.destination);

  osc.start(now);
  osc.stop(now + durationSec + 0.1);
}

/**
 * Simulates drum hits (Kick, Snare, Hi-Hat).
 */
function playDrumSound(ctx: AudioContext, type: 'kick' | 'snare' | 'hihat') {
  const now = ctx.currentTime;

  if (type === 'kick') {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.frequency.setValueAtTime(130, now);
    osc.frequency.exponentialRampToValueAtTime(getMidiNoteFrequency432(36) * 0.8, now + 0.15); // tuned towards low D9 432Hz harmonic
    gain.gain.setValueAtTime(0.8, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.25);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start(now);
    osc.stop(now + 0.26);
  } else if (type === 'snare') {
    // Noise buffer + body tone
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'triangle';
    osc.frequency.setValueAtTime(180, now);
    osc.frequency.exponentialRampToValueAtTime(80, now + 0.1);
    gain.gain.setValueAtTime(0.5, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.15);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start(now);
    osc.stop(now + 0.16);
  } else {
    // Hi-hat
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'square';
    osc.frequency.setValueAtTime(8000, now);
    gain.gain.setValueAtTime(0.15, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.05);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start(now);
    osc.stop(now + 0.06);
  }
}

/**
 * Plays a full procedural pattern generated by Horizon Engine.
 */
export function playProceduralPattern(genre: string, bpm = 80, onProgress?: (currentBar: number) => void) {
  stopAudioPlayback();
  const ctx = getAudioContext();
  isPlaying = true;

  const secondsPerBeat = 60 / bpm;
  const bars = 4;
  const totalBeats = bars * 4;

  for (let beat = 0; beat < totalBeats; beat++) {
    const timeMs = beat * secondsPerBeat * 1000;
    const barNum = Math.floor(beat / 4);

    const timeoutId = window.setTimeout(() => {
      if (!isPlaying) return;
      if (onProgress) onProgress(barNum + 1);

      // Drum sequencing
      if (genre.includes('reggae') || genre.includes('dub')) {
        // One drop: kick and snare rim on beat 3 (beat % 4 === 2)
        playDrumSound(ctx, 'hihat');
        if (beat % 4 === 2) {
          playDrumSound(ctx, 'kick');
          playDrumSound(ctx, 'snare');
        }
        // Skank chords on offbeats (delayed 0.5 beat)
        setTimeout(() => {
          if (!isPlaying) return;
          const chords = [
            [57, 60, 64], // Am
            [55, 59, 62], // G
            [53, 57, 60], // F
            [52, 55, 59]  // Em
          ];
          const chord = chords[barNum % chords.length];
          chord.forEach(n => play432HzTone(n, 0.22, 'triangle', 0.25));
        }, (secondsPerBeat * 0.5) * 1000);

        // Sub bass
        if (beat % 2 === 0) {
          const roots = [33, 31, 29, 28];
          play432HzTone(roots[barNum % roots.length], secondsPerBeat * 1.6, 'sine', 0.85);
        }
      } else if (genre.includes('g-funk') || genre.includes('funk')) {
        // G-Funk beat: Kick on 1 and 2.5, Clap on 2 and 4
        if (beat % 4 === 0) playDrumSound(ctx, 'kick');
        if (beat % 4 === 1 || beat % 4 === 3) playDrumSound(ctx, 'snare');
        playDrumSound(ctx, 'hihat');

        // Bouncy bass
        const gBassRoots = [30, 30, 33, 35];
        play432HzTone(gBassRoots[beat % gBassRoots.length], secondsPerBeat * 0.7, 'sawtooth', 0.5);

        // High whiny sine lead whistle
        if (barNum >= 1 && (beat % 2 === 0)) {
          const whistleNotes = [81, 84, 86, 88];
          play432HzTone(whistleNotes[beat % whistleNotes.length], secondsPerBeat * 1.8, 'sine', 0.4);
        }
      } else {
        // Trip-hop
        if (beat % 4 === 0) playDrumSound(ctx, 'kick');
        if (beat % 4 === 1 || beat % 4 === 3) playDrumSound(ctx, 'snare');
        playDrumSound(ctx, 'hihat');

        // Rhodes chords
        if (beat % 4 === 0) {
          const tripChords = [
            [50, 53, 57, 60], // Dm7
            [46, 50, 53, 57], // Bbmaj7
            [51, 55, 58, 62], // Gm7
            [45, 49, 52, 55]  // A7
          ];
          tripChords[barNum % tripChords.length].forEach(n => play432HzTone(n, secondsPerBeat * 3.4, 'sine', 0.3));
        }

        // Sub bass
        if (beat % 4 === 0 || beat % 4 === 2) {
          const tripRoots = [26, 22, 27, 21];
          play432HzTone(tripRoots[barNum % tripRoots.length], secondsPerBeat * 1.4, 'triangle', 0.7);
        }
      }
    }, timeMs);

    playbackTimeoutIds.push(timeoutId);
  }

  // End of loop
  const totalDurationMs = totalBeats * secondsPerBeat * 1000;
  const endTimeout = window.setTimeout(() => {
    isPlaying = false;
    if (onProgress) onProgress(0);
  }, totalDurationMs);
  playbackTimeoutIds.push(endTimeout);
}
